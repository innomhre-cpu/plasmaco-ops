"""Generates WinAnsi (cp1252) advance widths for Helvetica and Helvetica-Bold from the Adobe core AFM files
shipped with matplotlib. Output: core/domain/.../export/pdf/HelveticaMetrics.kt"""
import os, sys, matplotlib
from fontTools.agl import UV2AGL
afm_dir = os.path.join(os.path.dirname(matplotlib.__file__), 'mpl-data', 'fonts', 'pdfcorefonts')
def widths(fn):
    w = {}
    for line in open(os.path.join(afm_dir, fn), encoding='latin-1'):
        if line.startswith('C '):
            parts = dict(p.strip().split(' ', 1) for p in line.split(';') if p.strip() and ' ' in p.strip())
            w[parts['N']] = int(float(parts['WX']))
    return w
def table(w):
    out = []
    for code in range(32, 256):
        try: ch = bytes([code]).decode('cp1252')
        except UnicodeDecodeError: out.append(w.get('space', 278)); continue
        name = UV2AGL.get(ord(ch)) or ('space' if ch == '\xa0' else None)
        if ch == '\xa0': name = 'space'
        if ch == '\xad': name = 'hyphen'
        out.append(w.get(name, w.get('bullet', 350)))
    return out
reg, bold = table(widths('Helvetica.afm')), table(widths('Helvetica-Bold.afm'))
def fmt(a): return ',\n        '.join(', '.join(str(x) for x in a[i:i+16]) for i in range(0, len(a), 16))
out = sys.argv[1]
open(out, 'w').write(f'''package rw.plasmaco.ops.domain.export.pdf

// GENERATED by tools/legacy-analysis/gen_helvetica_metrics.py from the Adobe Core 14 AFM files.
// Advance widths (1/1000 em) for WinAnsiEncoding codes 32..255.
internal object HelveticaMetrics {{
    val REGULAR = intArrayOf(
        {fmt(reg)},
    )
    val BOLD = intArrayOf(
        {fmt(bold)},
    )
}}
''')
print('ok', len(reg), len(bold), reg[:5], bold[33-32])
