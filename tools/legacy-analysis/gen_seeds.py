"""Generates Kotlin seed data from the PLASMACO workbook analysis.

Inputs : iso.json (from iso_products.py) and wb_43.json (from parse_wb.py on the newest workbook).
Output : core/domain/src/main/kotlin/rw/plasmaco/ops/domain/master/Seeds.kt
Only verified workbook content is emitted: the ISO 4427-2 table and the product list of the
latest daily block (7 Oct 2026) with the minimum quantities found there.
"""
import json, re, sys
iso = json.load(open(sys.argv[1])); wb = json.load(open(sys.argv[2])); out = sys.argv[3]
rx = re.compile(r'DN\s*(\d+)\s*PN\s*([\d.]+)', re.I)
def pnt(p): return p.rstrip('0').rstrip('.') if '.' in p else p
lines = []
lines.append('package rw.plasmaco.ops.domain.master\n')
lines.append('import java.math.BigDecimal\n')
lines.append('// GENERATED by tools/legacy-analysis/gen_seeds.py from "Finished Goods & Raw Material Stock 2026" (-43, saved 8 Oct 2026).')
lines.append('// Do not edit by hand; regenerate from the workbook instead.\n')
lines.append('object Seeds {')
lines.append('    private fun d(s: String) = BigDecimal(s)')
lines.append('    /** Sheet "Rs iso 4427-2": mean OD limits, ovality, wall limits and kg per metre per DN x PN. */')
lines.append('    val ISO_4427_2: List<PipeSpec> = listOf(')
rows=[]
for k,v in iso.items():
    dnv, pn = k.split('|')
    def f(x): return 'null' if x is None else f'd("{x}")'
    rows.append(f'        PipeSpec({dnv}, d("{pn}"), d("{v["sdr"]}"), d("{v["od_min"]}"), d("{v["od_max"]}"), d("{v["ovality_max"]}"), {f(v["wall_min"])}, {f(v["wall_max"])}, {f(v["kg_per_m"])}),')
lines += rows
lines.append('    )\n')
# latest block product list
vis=[s for s in wb['sheets'] if s['state']!='hidden']
last=vis[-1]['blocks'][-1]
lines.append('    /** One entry per product row of the latest daily block (7 Oct 2026), in workbook order. */')
lines.append('    data class LegacyProduct(val legacyName: String, val dn: Int?, val pn: BigDecimal?, val workbookKgPerMetre: BigDecimal?, val isoKgPerMetre: BigDecimal?, val workbookMinQty: BigDecimal?)\n')
lines.append('    val PLASMACO_CATALOGUE: List<LegacyProduct> = listOf(')
for r in last['rows']:
    n=r['name']; m=rx.search(n)
    dnv = m.group(1) if m else None; pn = pnt(m.group(2)) if m else None
    isokg = iso.get(f'{int(dnv)}|{pn}',{}).get('kg_per_m') if m else None
    wf = r['kg_per_m'] if isinstance(r['kg_per_m'],(int,float)) else None
    mq = r['min_qty'] if isinstance(r['min_qty'],(int,float)) else None
    esc = n.replace('"','\\"')
    def q(x): return 'null' if x is None else f'd("{x}")'
    lines.append(f'        LegacyProduct("{esc}", {dnv if dnv else "null"}, {q(pn)}, {q(wf)}, {q(isokg)}, {q(mq)}),')
lines.append('    )')
lines.append('}')
open(out,'w').write('\n'.join(lines)+'\n')
print('wrote', out, len(rows), 'iso rows,', len(last['rows']), 'products')
